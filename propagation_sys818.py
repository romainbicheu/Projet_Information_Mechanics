"""## 2. Référence théorique : vitesse d'un pixel vs β²
Même logique que le script du prof : un pixel au centre d'une image 301×301, filtre construit dans la base DCT avec `t[0,0] = sqrt(1-β²)` (somme) et `t[0,1] = sqrt(β²)` (gradient), 10 convolutions + ReLU, vitesse = déplacement du centre de masse / nombre de couches. Théorie : (v/c)² = β², avec c = (w−1)/2.
"""

def measure_speed(k, beta2, n_steps=10, size=301):
    img = np.zeros((size, size)); mid = size // 2; img[mid, mid] = 1.
    x = tf.cast(tf.reshape(img, (1, size, size, 1)), tf.float32)
    t = np.zeros((k, k)); t[0, 1] = np.sqrt(beta2); t[0, 0] = np.sqrt(1 - beta2)
    filt = fft.idctn(t, norm="ortho")
    for n in range(n_steps + 1):
        x = x / tf.math.reduce_std(x)
        vals = x[0, size // 2, :, :]; vals = vals / tf.reduce_sum(vals)
        pos = np.expand_dims(np.linspace(-(size // 2), size // 2, size), -1).astype("float32")
        mean = float(tf.reduce_sum(pos * vals))
        if k == 2:                                   # cas 2×2 du prof : placé en 3×3, en alternant
            w = np.zeros((3, 3, 1, 1))
            if n % 2 == 0: w[1:, 0:2, 0, 0] = filt
            else:          w[0:2, 1:, 0, 0] = filt
        else:
            w = filt.reshape(k, k, 1, 1)
        x = tf.nn.relu(tf.nn.conv2d(x, tf.cast(w, tf.float32), strides=1, padding="SAME"))
    return mean / n_steps

STEP = 0.05                       # 0.01 comme le prof = plus long
