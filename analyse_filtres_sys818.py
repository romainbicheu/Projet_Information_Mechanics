"""## 4. Statistiques par couche (avec `getSymAntiSymTF` du prof)"""

POS = [(0,0),(0,1),(1,0),(1,1),(0,2),(2,0),(1,2),(2,1),(2,2)]       # même ordre que random_full.ipynb
