"""## 6. Énergie par composante DCT (dc = somme, c1/c2 = gradients du 1er ordre)"""

def dct_energy(stats_list):
    out = np.zeros(9)
    for s in stats_list:
        e = np.array([(s["dct"][i, j]**2).sum() for i, j in POS])
        out += e / e.sum()
    return out / len(stats_list)

